import 'package:flutter/material.dart';

@immutable
final class AppSpacing {
  const AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;

  static const EdgeInsets paddingXs = EdgeInsets.all(xs);
  static const EdgeInsets paddingSm = EdgeInsets.all(sm);
  static const EdgeInsets paddingMd = EdgeInsets.all(md);
  static const EdgeInsets paddingLg = EdgeInsets.all(lg);
  static const EdgeInsets paddingXl = EdgeInsets.all(xl);

  static const EdgeInsets paddingXsH = EdgeInsets.symmetric(horizontal: xs);
  static const EdgeInsets paddingSmH = EdgeInsets.symmetric(horizontal: sm);
  static const EdgeInsets paddingMdH = EdgeInsets.symmetric(horizontal: md);
  static const EdgeInsets paddingLgH = EdgeInsets.symmetric(horizontal: lg);
  static const EdgeInsets paddingXlH = EdgeInsets.symmetric(horizontal: xl);

  static const SizedBox gapXs = SizedBox(width: xs, height: xs);
  static const SizedBox gapSm = SizedBox(width: sm, height: sm);
  static const SizedBox gapMd = SizedBox(width: md, height: md);
  static const SizedBox gapLg = SizedBox(width: lg, height: lg);
  static const SizedBox gapXl = SizedBox(width: xl, height: xl);
  static const SizedBox gapXxl = SizedBox(width: xxl, height: xxl);
}
